function pack(startId, topic, difficulty, rows) {
  return rows.map((row, i) => ({
    id: startId + i,
    topic,
    difficulty,
    question: row[0],
    options: row[1],
    correctAnswer: row[2],
    explanation: row[3],
  }));
}

